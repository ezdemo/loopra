    // ==================== 路径安全校验 ====================

    /**
     * 将请求路径规范化为项目内的 Git 路径，并拒绝绝对路径、路径穿越和符号链接逃逸。
     * 空路径仅供查询整个仓库的接口使用。
     */
    private String validatePath(File workspaceDir, String path) {
        if (path == null) return null;
        String trimmed = path.trim();
        if (trimmed.isEmpty()) return "";

        Path file = resolveWorkspaceFile(workspaceDir, trimmed);
        return workspacePath(workspaceDir).relativize(file).toString().replace(File.separatorChar, '/');
    }

    private List<String> validatePaths(File workspaceDir, List<String> paths) {
        List<String> validated = new ArrayList<>(paths.size());
        for (String path : paths) {
            String value = validatePath(workspaceDir, path);
            if (value == null || value.isEmpty()) {
                throw new ServiceException("Invalid path");
            }
            validated.add(value);
        }
        return validated;
    }

    private Path resolveWorkspaceFile(File workspaceDir, String path) {
        try {
            Path workspace = workspacePath(workspaceDir);
            Path requested = Path.of(path);
            if (requested.isAbsolute()) {
                throw new ServiceException("Invalid path");
            }

            Path file = workspace.resolve(requested).normalize();
            if (!file.startsWith(workspace)) {
                throw new ServiceException("Invalid path");
            }

            // 对不存在的目标，验证最近的已有父目录，避免通过项目内的链接目录逃逸。
            Path existing = file;
            while (existing != null && !Files.exists(existing, LinkOption.NOFOLLOW_LINKS)) {
                existing = existing.getParent();
            }
            if (existing == null || !existing.toRealPath().startsWith(workspace)) {
                throw new ServiceException("Invalid path");
            }
            return file;
        } catch (InvalidPathException | IOException e) {
            throw new ServiceException("Invalid path");
        }
    }

    private Path workspacePath(File workspaceDir) {
        try {
            return workspaceDir.toPath().toRealPath();
        } catch (IOException e) {
            throw new ServiceException("项目不可访问");
        }
    }

    // ==================== AI 辅助工具方法 ====================

    /**
     * 获取项目中所有变更文件列表（含暂存、未暂存、未跟踪）。
     */
    private List<String> getChangedFiles(File workspaceDir) throws Exception {
        WorkspaceChanges changes = readWorkspaceChanges(workspaceDir);
        return java.util.stream.Stream.concat(changes.changed().stream(), changes.untracked().stream())
                .map(GitFileChangeDTO::path).distinct().toList();
    }

    /**
     * 获取最多 3 个文件的暂存和未暂存 diff，全部文件名由调用方单独发送。
     */
    private String getCommitDiff(File workspaceDir, List<String> files) {
        StringBuilder diffBuilder = new StringBuilder();
        int limit = Math.min(files.size(), MAX_COMMIT_DIFF_FILES);
        for (int i = 0; i < limit; i++) {
            String file = files.get(i);
            String staged = "";
            String unstaged = "";
            try {
                ProcessResult result = runGit(workspaceDir, "git", "diff", "--cached", "--", file);
                if (result.stdout != null) staged = result.stdout;
            } catch (Exception e) {
                log.debug("[git] 获取文件 {} 的 staged diff 失败: {}", file, e.getMessage());
            }
            try {
                ProcessResult result = runGit(workspaceDir, "git", "diff", "--", file);
                if (result.stdout != null) unstaged = result.stdout;
            } catch (Exception e) {
                log.debug("[git] 获取文件 {} 的 unstaged diff 失败: {}", file, e.getMessage());
            }

            String fileDiff = (staged + "\n" + unstaged).trim();
            if (!fileDiff.isEmpty()) {
                diffBuilder.append("# ").append(file).append("\n")
                        .append(truncateCommitDiff(fileDiff)).append("\n\n");
            }
        }
        return diffBuilder.toString().trim();
    }

    private static String truncateCommitDiff(String diff) {
        String[] lines = diff.split("\n", -1);
        String truncated = lines.length <= MAX_COMMIT_DIFF_LINES
                ? diff
                : String.join("\n", Arrays.copyOf(lines, MAX_COMMIT_DIFF_LINES))
                        + "\n... (diff 过长，仅保留前 " + MAX_COMMIT_DIFF_LINES + " 行)";
        if (truncated.length() <= MAX_COMMIT_DIFF_CHARS) return truncated;
        return truncated.substring(0, MAX_COMMIT_DIFF_CHARS)
                + "\n... (diff 过长，仅保留前 " + MAX_COMMIT_DIFF_CHARS + " 个字符)";
    }

    // ==================== JSON 解析工具方法 ====================

    /**
     * 安全解析 JSON body 为 ONode 对象，解析失败时记录日志并返回 null。
     */
    private ONode parseJsonBody(String body, String caller) {
        if (body == null || body.trim().isEmpty()) return null;
        try {
            ONode json = ONode.ofJson(body);
            if (json != null && json.isObject()) return json;
        } catch (Exception e) {
            log.debug("[git] {} 解析 JSON body 失败: {}", caller, e.getMessage());
        }
        return null;
    }

    /**
     * 从 ONode 对象中安全读取字符串字段，缺失或类型不符时返回 null。
     */
    private String readStringField(ONode json, String field) {
        if (json == null) return null;
        ONode node = json.get(field);
        if (node != null && node.isString()) {
            String value = node.getString();
            return value != null && !value.trim().isEmpty() ? value.trim() : null;
        }
        return null;
    }

    /**
     * 从 ONode 对象中安全读取字符串数组字段，缺失或类型不符时返回 null。
     */
    private List<String> readStringListField(ONode json, String field) {
        if (json == null) return null;
        ONode node = json.get(field);
        if (node != null && node.isArray()) {
            List<String> list = new ArrayList<>();
            for (ONode item : node.getArray()) {
                if (item.isString()) list.add(item.getString());
            }
            return list.isEmpty() ? null : list;
        }
        return null;
    }

    /**
     * 从 JSON 请求体中提取 path 字段。
     */
    private String extractPath(String body) {
        ONode json = parseJsonBody(body, "extractPath");
        return readStringField(json, "path");
    }

    /**
     * 简单 Git 命令执行 —— 用于只读查询，基于 runGit 的薄包装。
     */
    private String runGitSimple(String dir, String... args) {
        try {
            List<String> cmd = new ArrayList<>();
            cmd.add("git");
            Collections.addAll(cmd, args);
            ProcessResult result = runGit(new File(dir), cmd.toArray(new String[0]));
            return result.exitCode == 0 ? result.stdout : null;
        } catch (Exception e) {
            log.warn("[git] 执行失败: {}", e.getMessage());
            return null;
        }
    }

