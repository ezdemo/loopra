    /**
     * 获取当前 Git 分支名称。
     */
    public String getBranch(String workspaceHash) {
        String workspacePath = resolveWorkspace(workspaceHash);
        String branch = runGitSimple(workspacePath, "rev-parse", "--abbrev-ref", "HEAD");
        if (branch == null) {
            throw new ServiceException("无法获取 Git 分支信息，目录可能不是 Git 仓库");
        }
        return branch.trim();
    }

    /**
     * 获取 Git 变更文件列表（暂存、未暂存和未跟踪）。
     */
    public GitDiffDTO getDiff(String workspaceHash) {
        String workspacePath = resolveWorkspace(workspaceHash);

        String branch = runGitSimple(workspacePath, "rev-parse", "--abbrev-ref", "HEAD");
        try {
            WorkspaceChanges changes = readWorkspaceChanges(new File(workspacePath));
            return new GitDiffDTO(branch != null ? branch.trim() : "unknown", changes.changed(), changes.untracked(),
                    changes.changed().size() + changes.untracked().size());
        } catch (Exception error) {
            throw new ServiceException("无法读取项目 Git 改动: " + error.getMessage());
        }
    }

    /**
     * Git 综合状态检测 —— 四阶段检测：git 可用性 → 仓库状态 → 分支名 → 变更文件。
     */
    public GitStatusDTO getStatus(String workspaceHash) throws Exception {
        File workspaceDir = new File(resolveWorkspace(workspaceHash));

        // 1. 检测 git 是否可用
        try {
            ProcessResult checkGit = runGit(workspaceDir, "git", "--version");
            if (checkGit.exitCode != 0) {
                return new GitStatusDTO(false, false, null,
                        workspaceDir.getAbsolutePath(), List.of(), List.of(), null, null);
            }
        } catch (Exception e) {
            return new GitStatusDTO(false, false, null,
                    workspaceDir.getAbsolutePath(), List.of(), List.of(), null, null);
        }

        // 2. 检测是否是 git 仓库
        ProcessResult checkRepo = runGit(workspaceDir, "git", "rev-parse", "--is-inside-work-tree");
        if (checkRepo.exitCode != 0) {
            return new GitStatusDTO(true, false, null,
                    workspaceDir.getAbsolutePath(), List.of(), List.of(), null, null);
        }

        // 3. 获取分支名
        ProcessResult branchResult = runGit(workspaceDir, "git", "branch", "--show-current");
        String branch = branchResult.stdout.trim();
        if (branch.isEmpty()) branch = "master";

        // 4. 展开未跟踪目录，只返回当前项目内、相对项目的文件路径。
        WorkspaceChanges changes = readWorkspaceChanges(workspaceDir);

        // 5. 获取配置的模型与渠道
        Map<String, String> config = getGitConfig(workspaceHash);
        String model = config.get("model");
        String modelChannelId = config.get("modelChannelId");

        return new GitStatusDTO(true, true, branch,
                workspaceDir.getAbsolutePath(), changes.changed(), changes.untracked(), model, modelChannelId);
    }

    /**
     * NUL 分隔保留中文、空格、引号及换行等文件名，不依赖 Git 的显示转义。
     * porcelain 路径始终相对仓库根目录；剥离 prefix 后才是项目内路径。
     */
    private void parsePorcelainStatus(String porcelainOutput, String prefix,
                                       List<GitFileChangeDTO> changed,
                                       List<GitFileChangeDTO> untracked) {
        if (porcelainOutput == null || porcelainOutput.isEmpty()) return;
        String[] entries = porcelainOutput.split("\0", -1);
        for (int index = 0; index < entries.length; index++) {
            String line = entries[index];
            if (line.length() < MIN_STATUS_LINE_LENGTH) continue;

            String indexStatus = String.valueOf(line.charAt(0));
            String workStatus = String.valueOf(line.charAt(1));
            String filename = line.substring(3);
            // -z 重命名/复制记录先给出新路径，下一条是旧路径。
            if ("RC".contains(indexStatus) || "RC".contains(workStatus)) index++;
            if (!filename.startsWith(prefix)) continue;
            filename = filename.substring(prefix.length());
            if (filename.isEmpty()) continue;

            if ("?".equals(indexStatus) && "?".equals(workStatus)) {
                untracked.add(new GitFileChangeDTO(filename, indexStatus, workStatus, "U"));
            } else {
                String status = !" ".equals(indexStatus) && !"?".equals(indexStatus) ? indexStatus : workStatus;
                changed.add(new GitFileChangeDTO(filename, indexStatus, workStatus, status));
            }
        }
    }

    private record WorkspaceChanges(List<GitFileChangeDTO> changed, List<GitFileChangeDTO> untracked) { }

    private WorkspaceChanges readWorkspaceChanges(File workspaceDir) throws Exception {
        ProcessResult prefixResult = runGit(workspaceDir, "git", "rev-parse", "--show-prefix");
        if (prefixResult.exitCode != 0) throw new ServiceException("当前项目不在 Git 仓库中");
        String prefix = prefixResult.stdout.replaceFirst("\\r?\\n$", "");
        ProcessResult status = runGit(workspaceDir, "git", "status", "--porcelain=v1", "-z", "--untracked-files=all", "--", ".");
        if (status.exitCode != 0) throw new ServiceException("读取 Git 改动失败: " + status.stderr);
        List<GitFileChangeDTO> changed = new ArrayList<>(), untracked = new ArrayList<>();
        parsePorcelainStatus(status.stdout, prefix, changed, untracked);
        return new WorkspaceChanges(changed, untracked);
    }

    /**
     * 获取 Git Diff 内容 —— 分别执行未暂存变更和已暂存变更的 diff 查询，合并输出。
     * 对于未跟踪文件，返回文件内容作为新增的 diff。
     * 如果非 Git 管理或没有 diff，返回文件原文内容。
     */
    public GitDiffContentDTO getDiffContent(String workspaceHash, String path) throws Exception {
        File workspaceDir = new File(resolveWorkspace(workspaceHash));

        // 安全校验：防止路径穿越
        path = validatePath(workspaceDir, path);

        boolean hasPath = path != null && !path.isEmpty();

        // 检查是否是 Git 仓库
        ProcessResult checkRepo = runGit(workspaceDir, "git", "rev-parse", "--is-inside-work-tree");
        boolean isGitRepo = checkRepo.exitCode == 0;

        if (!isGitRepo) {
            // 非 Git 管理，返回原文内容
            return getOriginalContent(workspaceDir, path, hasPath);
        }

        // 未暂存的变更
        List<String> unstagedCmd = new ArrayList<>(Arrays.asList("git", "diff"));
        if (hasPath) { unstagedCmd.add("--"); unstagedCmd.add(path); }
        ProcessResult unstagedResult = runGit(workspaceDir, unstagedCmd.toArray(new String[0]));

        // 已暂存的变更
        List<String> stagedCmd = new ArrayList<>(Arrays.asList("git", "diff", "--cached"));
        if (hasPath) { stagedCmd.add("--"); stagedCmd.add(path); }
        ProcessResult stagedResult = runGit(workspaceDir, stagedCmd.toArray(new String[0]));

        // 合并 diff 输出
        String fullDiff = unstagedResult.stdout;
        if (!stagedResult.stdout.isEmpty()) {
            fullDiff += "\n" + stagedResult.stdout;
        }

        // 对于未跟踪文件，git diff 返回空，需要读取文件内容生成 diff
        if (hasPath && fullDiff.trim().isEmpty()) {
            // 检查文件是否未跟踪
            List<String> statusCmd = new ArrayList<>(Arrays.asList("git", "status", "--porcelain", "--", path));
            ProcessResult statusResult = runGit(workspaceDir, statusCmd.toArray(new String[0]));
            if (statusResult.exitCode == 0 && statusResult.stdout.trim().startsWith("??")) {
                // 文件未跟踪，读取文件内容生成 diff
                File file = resolveWorkspaceFile(workspaceDir, path).toFile();
                if (file.exists() && file.isFile()) {
                    try {
                        List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
                        int lineCount = lines.size();
                        // 限制最大行数
                        int maxLines = MAX_DIFF_LINES;
                        if (lineCount > maxLines) {
                            lines = lines.subList(0, maxLines);
                        }
                        StringBuilder diffBuilder = new StringBuilder();
                        diffBuilder.append("--- /dev/null\n");
                        diffBuilder.append("+++ b/").append(path).append("\n");
                        diffBuilder.append("@@ -0,0 +1,").append(lineCount).append(" @@\n");
                        for (String line : lines) {
                            diffBuilder.append("+").append(line).append("\n");
                        }
                        if (lineCount > maxLines) {
                            diffBuilder.append("\n... (文件过大，仅显示前 ").append(maxLines).append(" 行)");
                        }
                        fullDiff = diffBuilder.toString();
                    } catch (Exception e) {
                        // 读取失败，忽略
                        log.debug("[git] 读取未跟踪文件失败: {}", e.getMessage());
                    }
                }
            }
        }

        // 如果没有 diff 且指定了路径，返回原文内容
        if (hasPath && fullDiff.trim().isEmpty()) {
            return getOriginalContent(workspaceDir, path, true);
        }

        // 截断保护：单文件 diff 限制 2000 行
        if (hasPath) {
            String[] lines = fullDiff.split("\n");
            if (lines.length > MAX_DIFF_LINES) {
                fullDiff = String.join("\n", Arrays.copyOf(lines, MAX_DIFF_LINES))
                        + "\n\n... (差异过大，仅显示前 " + MAX_DIFF_LINES + " 行，请在终端查看完整 diff)";
            }
        }

        // stat 摘要
        List<String> statCmd = new ArrayList<>(Arrays.asList("git", "diff", "--stat"));
        if (hasPath) { statCmd.add("--"); statCmd.add(path); }
        ProcessResult statResult = runGit(workspaceDir, statCmd.toArray(new String[0]));

        List<String> statCachedCmd = new ArrayList<>(Arrays.asList("git", "diff", "--cached", "--stat"));
        if (hasPath) { statCachedCmd.add("--"); statCachedCmd.add(path); }
        ProcessResult statCachedResult = runGit(workspaceDir, statCachedCmd.toArray(new String[0]));

        String stat = statResult.stdout;
        if (!statCachedResult.stdout.isEmpty()) {
            stat += (stat.isEmpty() ? "" : "\n") + statCachedResult.stdout;
        }

        // 对于未跟踪文件，生成 stat 摘要
        if (hasPath && stat.trim().isEmpty()) {
            // 再次检查未跟踪状态（可能已被上面的 diff 处理）
            List<String> statusCmd2 = new ArrayList<>(Arrays.asList("git", "status", "--porcelain", "--", path));
            ProcessResult statusResult2 = runGit(workspaceDir, statusCmd2.toArray(new String[0]));
            if (statusResult2.exitCode == 0 && statusResult2.stdout.trim().startsWith("??")) {
                File file = resolveWorkspaceFile(workspaceDir, path).toFile();
                if (file.exists() && file.isFile()) {
                    try {
                        List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
                        int lineCount = lines.size();
                        stat = path + " | " + lineCount + " ++";
                    } catch (Exception e) {
                        // 忽略
                    }
                }
            }
        }

        return new GitDiffContentDTO(fullDiff, stat);
    }

    /**
     * 获取文件原文内容 —— 用于非 Git 管理或没有 diff 的情况。
     */
    private GitDiffContentDTO getOriginalContent(File workspaceDir, String path, boolean hasPath) {
        if (!hasPath) {
            // 没有指定路径，返回空内容
            return new GitDiffContentDTO("", "");
        }

        File file = resolveWorkspaceFile(workspaceDir, path).toFile();
        if (!file.exists() || !file.isFile()) {
            // 文件不存在，返回空内容
            return new GitDiffContentDTO("", "");
        }

        try {
            List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
            int lineCount = lines.size();
            String content = String.join("\n", lines);
            String stat = path + " | " + lineCount + " lines";
            return new GitDiffContentDTO(content, stat);
        } catch (Exception e) {
            log.debug("[git] 读取文件失败: {}", e.getMessage());
            return new GitDiffContentDTO("", "");
        }
    }

    /**
     * 获取 Git 仓库中指定版本的文件内容。
     */
    public GitFileContentDTO getFileContent(String workspaceHash, String path, String ref) throws Exception {
        File workspaceDir = new File(resolveWorkspace(workspaceHash));

        path = validatePath(workspaceDir, path);
        if (path == null || path.isEmpty()) {
            throw new ServiceException("Invalid path");
        }
        if (ref == null || ref.isEmpty()) ref = "HEAD";

        ProcessResult result = runGit(workspaceDir, "git", "show", ref + ":" + path);

        if (result.exitCode != 0) {
            throw new ServiceException("File not found: " + result.stderr);
        }

        return new GitFileContentDTO(result.stdout);
    }

    /**
     * 读取项目当前文件内容，用于前端代码预览，不依赖 Git 状态或提交历史。
     */
    public WorkingFileContentDTO getWorkingFileContent(String workspaceHash, String path) throws Exception {
        if (path == null || path.isBlank()) {
            throw new ServiceException("Invalid path");
        }

        java.nio.file.Path workspace = java.nio.file.Paths.get(resolveWorkspace(workspaceHash)).toAbsolutePath().normalize();
        String filePath = path.trim().replaceFirst(":\\d+$", "");
        java.nio.file.Path requested = java.nio.file.Paths.get(filePath);
        java.nio.file.Path file = (requested.isAbsolute() ? requested : workspace.resolve(requested)).normalize();
        if (!file.startsWith(workspace)) {
            throw new ServiceException("Invalid path");
        }
        if (!Files.isRegularFile(file)) {
            return new WorkingFileContentDTO(null, false, "当前项目中未找到此文件，可能已移动或删除。");
        }
        if (Files.size(file) > 1024 * 1024) {
            return new WorkingFileContentDTO(null, true, "文件过大，无法预览（最大 1 MB）。");
        }
        return new WorkingFileContentDTO(Files.readString(file, StandardCharsets.UTF_8), true, null);
    }

    /**
     * 获取 Git 提交历史记录，默认返回最近 50 条。
     * <p>
     * 使用 git log 自定义格式输出，按提交时间倒序排列。
     * </p>
     */
    public GitCommitDTO.ListWrapper getCommitHistory(String workspaceHash, Integer limit) {
        String workspacePath = resolveWorkspace(workspaceHash);
        if (limit == null || limit <= 0) limit = 50;

        // 自定义格式: 完整哈希|短哈希|作者|邮箱|日期|消息
        // 使用 %x1F (Unit Separator) 作为字段分隔，避免消息中的特殊字符干扰
        String format = "%H%x1F%h%x1F%an%x1F%ae%x1F%ai%x1F%s";
        String raw = runGitSimple(workspacePath,
                "log", "-" + limit, "--format=" + format);

        List<GitCommitDTO> commits = new ArrayList<>();
        if (raw != null && !raw.trim().isEmpty()) {
            for (String line : raw.split("\n")) {
                if (line.trim().isEmpty()) continue;
                String[] parts = line.split("\u001F", 6);
                if (parts.length < 6) continue;
                commits.add(new GitCommitDTO(
                        parts[0],   // 完整哈希
                        parts[1],   // 短哈希
                        parts[2],   // 作者
                        parts[3],   // 邮箱
                        parts[4],   // 日期（ISO 8601）
                        parts[5]    // 提交消息
                ));
            }
        }
        return new GitCommitDTO.ListWrapper(commits, commits.size());
    }

    /**
     * 初始化 Git 仓库 —— git init + 自动生成 .gitignore + 可选初始提交。
     */
    public Map<String, Object> initRepo(String workspaceHash, Boolean initialCommit) throws Exception {
        File workspaceDir = new File(resolveWorkspace(workspaceHash));

        // 安全校验：确认不是已有仓库
        ProcessResult check = runGit(workspaceDir, "git", "rev-parse", "--is-inside-work-tree");
        if (check.exitCode == 0) {
            throw new ServiceException("Already a git repository");
        }

        // 执行 git init
        ProcessResult initResult = runGit(workspaceDir, "git", "init");
        if (initResult.exitCode != 0) {
            throw new ServiceException("git init failed: " + initResult.stderr);
        }

        // 自动生成 .gitignore（仅当文件不存在时）
        File gitignore = new File(workspaceDir, ".gitignore");
        if (!gitignore.exists()) {
            Files.writeString(gitignore.toPath(), DEFAULT_GITIGNORE, StandardCharsets.UTF_8);
        }

        // 可选：执行 initial commit
        if (Boolean.TRUE.equals(initialCommit)) {
            runGit(workspaceDir, "git", "add", "-A");
            runGit(workspaceDir, "git", "-c", "user.name=" + DEFAULT_AUTHOR_NAME,
                    "-c", "user.email=" + DEFAULT_AUTHOR_EMAIL,
                    "commit", "-m", "Initial commit");
        }

        Map<String, Object> data = new LinkedHashMap<>();
        data.put("initialized", true);

        ProcessResult branchResult = runGit(workspaceDir, "git", "branch", "--show-current");
        String branch = branchResult.stdout.trim();
        data.put("branch", branch.isEmpty() ? "master" : branch);

        return data;
    }

    /**
     * Git 提交 —— 解析 body 中的 message 和 files，支持精确文件列表或全量 add -A。
     */
    public GitCommitResultDTO commit(String workspaceHash, String body) throws Exception {
        File workspaceDir = new File(resolveWorkspace(workspaceHash));

        // 安全校验：确认是 git 仓库
        ProcessResult check = runGit(workspaceDir, "git", "rev-parse", "--is-inside-work-tree");
        if (check.exitCode != 0) {
            throw new ServiceException("Not a git repository");
        }

        // 解析 JSON body
        ONode json = parseJsonBody(body, "commit");
        String message = readStringField(json, "message");
        List<String> files = readStringListField(json, "files");
        String authorName = readStringField(json, "authorName");
        String authorEmail = readStringField(json, "authorEmail");

        if (message == null || message.trim().isEmpty()) {
            throw new ServiceException("Commit message is required");
        }

        // git add：有指定文件时精确暂存，否则只提交已暂存的文件
        if (files != null && !files.isEmpty()) {
            files = validatePaths(workspaceDir, files);
            // 先清空暂存区，避免之前已暂存的非选中文件被一起提交
            runGit(workspaceDir, "git", "reset", "HEAD", "--");

            List<String> addCmd = new ArrayList<>();
            addCmd.add("git");
            addCmd.add("add");
            addCmd.add("--");
            addCmd.addAll(files);
            ProcessResult addResult = runGit(workspaceDir, addCmd.toArray(new String[0]));
            if (addResult.exitCode != 0) {
                throw new ServiceException("git add failed: " + addResult.stderr);
            }
        }

        // 构建 git commit 命令（动态 author）
        List<String> commitCmd = new ArrayList<>();
        commitCmd.add("git");
        commitCmd.add("-c");
        commitCmd.add("user.name=" + (authorName != null && !authorName.trim().isEmpty() ? authorName.trim() : DEFAULT_AUTHOR_NAME));
        commitCmd.add("-c");
        commitCmd.add("user.email=" + (authorEmail != null && !authorEmail.trim().isEmpty() ? authorEmail.trim() : DEFAULT_AUTHOR_EMAIL));
        commitCmd.add("commit");
        commitCmd.add("-m");
        commitCmd.add(message);
        ProcessResult commitResult = runGit(workspaceDir, commitCmd.toArray(new String[0]));

        if (commitResult.exitCode != 0) {
            throw new ServiceException("git commit failed: " + commitResult.stderr);
        }

        return new GitCommitResultDTO(commitResult.stdout);
    }

    /**
     * 获取提交作者配置（优先级：已保存配置 > git config > Loopra 默认）。
     */
    public Map<String, String> getGitConfig(String workspaceHash) {
        String workspacePath = resolveWorkspace(workspaceHash);
        File workspaceDir = new File(workspacePath);

        Map<String, String> result = new LinkedHashMap<>();

        // 1) 读取已保存的 .loopra/git-author.json
        File configFile = new File(workspaceDir, ".loopra/git-author.json");
        if (configFile.exists()) {
            try {
                String json = Files.readString(configFile.toPath(), StandardCharsets.UTF_8);
                ONode node = ONode.ofJson(json);
                if (node != null && node.isObject()) {
                    ONode nameNode = node.get("authorName");
                    if (nameNode != null && nameNode.isString() && !nameNode.getString().trim().isEmpty()) {
                        result.put("authorName", nameNode.getString().trim());
                    }
                    ONode emailNode = node.get("authorEmail");
                    if (emailNode != null && emailNode.isString() && !emailNode.getString().trim().isEmpty()) {
                        result.put("authorEmail", emailNode.getString().trim());
                    }
                    ONode modelNode = node.get("model");
                    if (modelNode != null && modelNode.isString() && !modelNode.getString().trim().isEmpty()) {
                        result.put("model", modelNode.getString().trim());
                    }
                    ONode channelNode = node.get("modelChannelId");
                    if (channelNode != null && channelNode.isString() && !channelNode.getString().trim().isEmpty()) {
                        result.put("modelChannelId", channelNode.getString().trim());
                    }
                }
            } catch (Exception e) {
                log.debug("[git] 读取 git-author.json 失败: {}", e.getMessage());
            }
        }

        // 2) 已保存配置缺少的字段，从 git config 补充
        if (!result.containsKey("authorName") || result.get("authorName") == null || result.get("authorName").isEmpty()) {
            String name = runGitSimple(workspacePath, "config", "user.name");
            if (name != null && !name.trim().isEmpty()) {
                result.put("authorName", name.trim());
            }
        }
        if (!result.containsKey("authorEmail") || result.get("authorEmail") == null || result.get("authorEmail").isEmpty()) {
            String email = runGitSimple(workspacePath, "config", "user.email");
            if (email != null && !email.trim().isEmpty()) {
                result.put("authorEmail", email.trim());
            }
        }

        // 3) 仍缺失的字段，回退到 Loopra 默认值
        if (!result.containsKey("authorName") || result.get("authorName") == null || result.get("authorName").isEmpty()) {
            result.put("authorName", DEFAULT_AUTHOR_NAME);
        }
        if (!result.containsKey("authorEmail") || result.get("authorEmail") == null || result.get("authorEmail").isEmpty()) {
            result.put("authorEmail", DEFAULT_AUTHOR_EMAIL);
        }

        // 4) 模型字段：如果未配置，使用当前全局模型
        if (!result.containsKey("model") || result.get("model") == null || result.get("model").isEmpty()) {
            result.put("model", agentService.getSharedModel());
        }
        // 4.1) 模型渠道字段：如果未配置，回退到当前激活渠道
        if (!result.containsKey("modelChannelId") || result.get("modelChannelId") == null || result.get("modelChannelId").isEmpty()) {
            LoopraConfig cfg = ConfigService.getConfig();
            if (cfg != null) {
                result.put("modelChannelId", cfg.modelChannelId());
            }
        }

        return result;
    }

