"""Fetch pinned upstream ripgrep binaries and generate platform-specific Go embeds."""

import argparse
import concurrent.futures
import gzip
import hashlib
import io
import json
from pathlib import Path
import tarfile
import time
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "internal" / "infrastructure" / "ripgrep"
MANIFEST = PACKAGE / "manifest.json"


def download(url, no_proxy):
    handlers = [urllib.request.ProxyHandler({})] if no_proxy else []
    opener = urllib.request.build_opener(*handlers)
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/octet-stream",
            "User-Agent": "looprax-vendor-ripgrep",
        },
    )
    for attempt in range(3):
        try:
            with opener.open(request, timeout=30) as response:
                deadline = time.monotonic() + 90
                chunks = []
                while chunk := response.read1(64 * 1024):
                    chunks.append(chunk)
                    if time.monotonic() > deadline:
                        raise TimeoutError("ripgrep archive download exceeded 90 seconds")
                return b"".join(chunks)
        except Exception as error:
            if attempt == 2:
                raise
            print(f"Retrying asset download: {error}", flush=True)
            time.sleep(attempt + 1)


def write_embed(platform):
    build_tag = f'{platform["goos"]} && {platform["goarch"]}'
    if platform["goarch"] == "arm":
        build_tag += " && arm.7"
    go_source = f'''// Code generated by scripts/vendor-ripgrep.py; DO NOT EDIT.
//go:build {build_tag}

package ripgrep

import _ "embed"

//go:embed assets/{platform["goos"]}_{platform["goarch"]}/rg.gz
var embeddedGzip []byte

const binarySHA256 = "{platform["binary_sha256"]}"
'''
    (PACKAGE / f'embed_{platform["goos"]}_{platform["goarch"]}.go').write_text(
        go_source, encoding="utf-8", newline="\n"
    )


def vendor(platform, manifest, no_proxy, archive_dir):
    version = manifest["version"]
    target = platform["target"]
    extension = "zip" if platform["goos"] == "windows" else "tar.gz"
    archive_name = f"ripgrep-{version}-{target}.{extension}"
    platform["archive"] = archive_name
    platform["source"] = (
        f'https://github.com/{manifest["repository"]}/releases/download/'
        f"{version}/{archive_name}"
    )
    url = (
        f'https://api.github.com/repos/{manifest["repository"]}/releases/assets/'
        f'{platform["asset_id"]}?download=1'
    )
    asset_dir = PACKAGE / "assets" / f'{platform["goos"]}_{platform["goarch"]}'
    compressed_path = asset_dir / "rg.gz"
    if compressed_path.exists() and platform.get("binary_sha256"):
        binary = gzip.decompress(compressed_path.read_bytes())
        if hashlib.sha256(binary).hexdigest() == platform["binary_sha256"]:
            write_embed(platform)
            print(f'{platform["goos"]}/{platform["goarch"]}: verified existing asset', flush=True)
            return None
    local_archive = Path(archive_dir) / archive_name if archive_dir else None
    archive = local_archive.read_bytes() if local_archive and local_archive.exists() else download(url, no_proxy)
    actual = hashlib.sha256(archive).hexdigest()
    if actual != platform["archive_sha256"]:
        raise ValueError(f"{archive_name}: SHA-256 mismatch: {actual}")

    # Read members directly; never extract untrusted archive paths onto disk.
    if extension == "zip":
        with zipfile.ZipFile(io.BytesIO(archive)) as source:
            members = {Path(name).name: source.read(name)
                       for name in source.namelist() if not name.endswith("/")}
    else:
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as source:
            members = {Path(member.name).name: source.extractfile(member).read()
                       for member in source.getmembers() if member.isfile()}
    executable = "rg.exe" if platform["goos"] == "windows" else "rg"
    binary = members[executable]
    platform["binary_sha256"] = hashlib.sha256(binary).hexdigest()
    asset_dir.mkdir(parents=True, exist_ok=True)
    compressed = io.BytesIO()
    with gzip.GzipFile(fileobj=compressed, filename="", mode="wb", mtime=0) as output:
        output.write(binary)
    (asset_dir / "rg.gz").write_bytes(compressed.getvalue())
    write_embed(platform)
    print(f'{platform["goos"]}/{platform["goarch"]}: verified {len(binary)} bytes', flush=True)
    return members


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-proxy", action="store_true",
                        help="download without environment/system HTTP proxies")
    parser.add_argument("--archive-dir",
                        help="read pinned release archives from this directory before downloading")
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as executor:
        futures = [
            executor.submit(vendor, platform, manifest, args.no_proxy, args.archive_dir)
            for platform in manifest["platforms"]
        ]
        archives = [future.result() for future in futures]
    licenses = PACKAGE / "licenses"
    licenses.mkdir(parents=True, exist_ok=True)
    source = next((archive for archive in archives if archive is not None), None)
    for name in ("COPYING", "LICENSE-MIT", "UNLICENSE"):
        if source is not None:
            (licenses / name).write_bytes(source[name])
        elif not (licenses / name).is_file():
            raise ValueError(f"Missing license {name}; provide a pinned release archive")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n",
                        encoding="utf-8", newline="\n")
    (PACKAGE / "version.go").write_text(
        '// Code generated by scripts/vendor-ripgrep.py; DO NOT EDIT.\n\n'
        f'package ripgrep\n\nconst Version = "{manifest["version"]}"\n',
        encoding="utf-8", newline="\n",
    )


if __name__ == "__main__":
    main()
