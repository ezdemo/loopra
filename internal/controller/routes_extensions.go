package controller

func (s *Controller) registerExtensionsRoutes(api *apiRouter) {
	readRoute(api, "/plugins", s.action((*Controller).pluginsController))
	readRoute(api, "/plugins/external", s.action((*Controller).pluginsController))
	readRoute(api, "/plugins/*", s.action((*Controller).pluginsController))
	api.POST("/plugins/", s.action((*Controller).pluginsController))
	api.POST("/plugins/*", s.action((*Controller).pluginsController))
	readRoute(api, "/extpacks", s.action((*Controller).extpacksController))
	api.POST("/extpacks/", s.action((*Controller).extpacksController))
	api.POST("/extpacks/*", s.action((*Controller).extpacksController))
	readRoute(api, "/skill-market/", s.action((*Controller).skillMarketController))
	readRoute(api, "/skill-market/*", s.action((*Controller).skillMarketController))
	api.POST("/skill-market/", s.action((*Controller).skillMarketController))
	api.POST("/skill-market/*", s.action((*Controller).skillMarketController))
	readRoute(api, "/openapi/", s.action((*Controller).openApiController))
	readRoute(api, "/openapi/*", s.action((*Controller).openApiController))
	api.POST("/openapi/", s.action((*Controller).openApiController))
	api.POST("/openapi/*", s.action((*Controller).openApiController))
	api.PUT("/openapi/", s.action((*Controller).openApiController))
	api.PUT("/openapi/*", s.action((*Controller).openApiController))
	api.DELETE("/openapi/", s.action((*Controller).openApiController))
	api.DELETE("/openapi/*", s.action((*Controller).openApiController))
	readRoute(api, "/mcp/", s.action((*Controller).mcpController))
	readRoute(api, "/mcp/*", s.action((*Controller).mcpController))
	api.POST("/mcp/", s.action((*Controller).mcpController))
	api.POST("/mcp/*", s.action((*Controller).mcpController))
	api.PUT("/mcp/", s.action((*Controller).mcpController))
	api.PUT("/mcp/*", s.action((*Controller).mcpController))
	readRoute(api, "/mcp", s.action((*Controller).mcpController))

	// Preserve the canonical slash redirects of the existing API.
	s.canonicalRedirect("DELETE", "/api/openapi")
	s.canonicalRedirect("GET", "/api/openapi")
	s.canonicalRedirect("GET", "/api/skill-market")
	s.canonicalRedirect("HEAD", "/api/openapi")
	s.canonicalRedirect("HEAD", "/api/skill-market")
	s.canonicalRedirect("POST", "/api/extpacks")
	s.canonicalRedirect("POST", "/api/mcp")
	s.canonicalRedirect("POST", "/api/openapi")
	s.canonicalRedirect("POST", "/api/plugins")
	s.canonicalRedirect("POST", "/api/skill-market")
	s.canonicalRedirect("PUT", "/api/mcp")
	s.canonicalRedirect("PUT", "/api/openapi")
}
