package controller

func (s *Controller) registerAgentRoutes(api *apiRouter) {
	readRoute(api, "/agent/status", s.action((*Controller).agentStatusController))
	readRoute(api, "/agent/session-status", s.action((*Controller).agentSessionStatusController))
	readRoute(api, "/agent/history", s.action((*Controller).agentHistoryController))
	readRoute(api, "/agent/history/events", s.action((*Controller).agentHistoryController))
	readRoute(api, "/agent/bash-sessions", s.action((*Controller).bashSessionsController))
	readRoute(api, "/agent/bash-sessions/log", s.action((*Controller).bashSessionsController))
	api.POST("/agent/bash-sessions/terminate", s.action((*Controller).bashSessionsController))
	readRoute(api, "/agent-engines", s.action((*Controller).agentEnginesController))
	readRoute(api, "/agent-engines/", s.action((*Controller).agentEnginesDeepController))
	readRoute(api, "/agent-engines/*", s.action((*Controller).agentEnginesDeepController))
	api.POST("/agent-engines/", s.action((*Controller).agentEnginesDeepController))
	api.POST("/agent-engines/*", s.action((*Controller).agentEnginesDeepController))
	api.PUT("/agent-engines/", s.action((*Controller).agentEnginesDeepController))
	api.PUT("/agent-engines/*", s.action((*Controller).agentEnginesDeepController))
	readRoute(api, "/sub-agents", s.action((*Controller).subAgentsController))
	api.PUT("/sub-agents", s.action((*Controller).subAgentsController))
	readRoute(api, "/sub-agents/denied-tools", s.action((*Controller).subAgentsController))
	readRoute(api, "/sub-sessions", s.action((*Controller).subSessionsController))
	readRoute(api, "/sub-sessions/", s.action((*Controller).subSessionsController))
	readRoute(api, "/sub-sessions/*", s.action((*Controller).subSessionsController))
	api.POST("/sub-sessions/", s.action((*Controller).subSessionsController))
	api.POST("/sub-sessions/*", s.action((*Controller).subSessionsController))
	api.DELETE("/sub-sessions/", s.action((*Controller).subSessionsController))
	api.DELETE("/sub-sessions/*", s.action((*Controller).subSessionsController))
	readRoute(api, "/agent/mode", s.action((*Controller).agentDeepController))
	api.POST("/agent/mode", s.action((*Controller).agentDeepController))
	readRoute(api, "/agent/commands", s.action((*Controller).agentDeepController))
	readRoute(api, "/agent/acp-state", s.action((*Controller).agentDeepController))
	readRoute(api, "/agent/prompt", s.action((*Controller).agentDeepController))
	readRoute(api, "/agent/project-capabilities", s.action((*Controller).agentDeepController))
	api.POST("/agent/project-capabilities/refresh", s.action((*Controller).agentDeepController))
	readRoute(api, "/agent/skills", s.action((*Controller).agentDeepController))

	// Preserve the canonical slash redirects of the existing API.
	s.canonicalRedirect("DELETE", "/api/sub-sessions")
	s.canonicalRedirect("POST", "/api/agent-engines")
	s.canonicalRedirect("POST", "/api/sub-sessions")
	s.canonicalRedirect("PUT", "/api/agent-engines")
}
