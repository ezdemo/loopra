const gitignoreTemplate = `# Auto-generated by Loopra
.git/
.idea/
.soloncode/
.gradle/
.mvn/
node_modules/
target/
build/
__pycache__/
*.class
*.jar
*.log
`

type InitResult struct {
	Initialized bool   `json:"initialized"`
	Branch      string `json:"branch"`
}

// Init 初始化仓库。initialCommit 为真时用 Loopra 默认身份做一次提交。
func Init(dir string, initialCommit bool) (InitResult, error) {
	if gitops.IsRepo(dir) {
		return InitResult{}, fail(http.StatusBadRequest, "Already a git repository")
	}
	run := gitops.Runner{Dir: dir}
	if _, _, err := run.Git(gitops.TimeoutQuery, "init"); err != nil {
		return InitResult{}, fail(http.StatusBadRequest, "Git 初始化失败: "+err.Error())
	}
	ignore := filepath.Join(dir, ".gitignore")
	if _, err := os.Stat(ignore); os.IsNotExist(err) {
		_ = os.WriteFile(ignore, []byte(gitignoreTemplate), 0o644)
	}
	branch := ""
	if out, err := run.Line(gitops.TimeoutQuery, "branch", "--show-current"); err == nil && out != "" {
		branch = out
	} else {
		branch = "master"
	}
	if initialCommit {
		run.Git(gitops.TimeoutQuery, "add", "-A")
		run.Git(gitops.TimeoutQuery, "-c", "user.name="+defaultAuthorName,
			"-c", "user.email="+defaultAuthorEmail, "commit", "-m", "Initial commit")
	}
	return InitResult{Initialized: true, Branch: branch}, nil
}

type CommitInput struct {
	Message     string   `json:"message"`
	Files       []string `json:"files"`
	AuthorName  string   `json:"authorName"`
	AuthorEmail string   `json:"authorEmail"`
}

// Commit 提交暂存内容。指定文件时先 reset 再 add。
func Commit(dir string, in CommitInput, defaults Defaults) (string, error) {
	if !gitops.IsRepo(dir) {
		return "", fail(http.StatusBadRequest, "Not a git repository")
	}
	if strings.TrimSpace(in.Message) == "" {
		return "", fail(http.StatusBadRequest, "Commit message is required")
	}
	run := gitops.Runner{Dir: dir}
	if len(in.Files) > 0 {
		validated, err := validateFiles(dir, in.Files)
		if err != nil {
			return "", err
		}
		run.Git(gitops.TimeoutQuery, "reset", "HEAD", "--")
		args := append([]string{"add", "--"}, validated...)
		if _, stderr, err := run.Git(gitops.TimeoutQuery, args...); err != nil {
			return "", fail(http.StatusBadRequest, "git add failed: "+stderr)
		}
	}
	author := AuthorConfig(dir, defaults)
	name, email := author["authorName"], author["authorEmail"]
	if strings.TrimSpace(in.AuthorName) != "" {
		name = in.AuthorName
	}
	if strings.TrimSpace(in.AuthorEmail) != "" {
		email = in.AuthorEmail
	}
	stdout, stderr, err := run.Git(gitops.TimeoutQuery,
		"-c", "user.name="+name, "-c", "user.email="+email,
		"commit", "-m", in.Message)
	if err != nil {
		return "", fail(http.StatusBadRequest, "git commit failed: "+stderr)
	}
	return stdout, nil
}

// CommitAll 提交隔离环境：未指定文件时 add -A，作者取仓库 git config。
func CommitAll(dir string, message string, files []string) (string, error) {
	if !gitops.IsRepo(dir) {
		return "", fail(http.StatusBadRequest, "Not a git repository")
	}
	if strings.TrimSpace(message) == "" {
		return "", fail(http.StatusBadRequest, "提交信息不能为空")
	}
	run := gitops.Runner{Dir: dir}
	if len(files) > 0 {
		validated, err := validateFiles(dir, files)
		if err != nil {
			return "", err
		}
		args := append([]string{"add", "--"}, validated...)
		if _, stderr, err := run.Git(gitops.TimeoutQuery, args...); err != nil {
			return "", fail(http.StatusBadRequest, "git add failed: "+stderr)
		}
	} else if _, stderr, err := run.Git(gitops.TimeoutQuery, "add", "-A"); err != nil {
		return "", fail(http.StatusBadRequest, "git add failed: "+stderr)
	}
	name, email := "", ""
	if out, err := run.Line(gitops.TimeoutQuery, "config", "user.name"); err == nil {
		name = out
	}
	if out, err := run.Line(gitops.TimeoutQuery, "config", "user.email"); err == nil {
		email = out
	}
	if strings.TrimSpace(name) == "" {
		name = defaultAuthorName
	}
	if strings.TrimSpace(email) == "" {
		email = defaultAuthorEmail
	}
	stdout, stderr, err := run.Git(gitops.TimeoutQuery,
		"-c", "user.name="+name, "-c", "user.email="+email,
		"commit", "-m", strings.TrimSpace(message))
	if err != nil {
		return "", fail(http.StatusBadRequest, "git commit failed: "+stderr)
	}
	if strings.TrimSpace(stdout) == "" {
		stdout = strings.TrimSpace(stderr)
	}
	return stdout, nil
}

// Toggle 翻转路径的暂存状态。staged 为空时按 porcelain 推断。
func Toggle(dir, path string, staged *bool) (clean, state string, err error) {
	if !gitops.IsRepo(dir) {
		return "", "", fail(http.StatusBadRequest, "Not a git repository")
	}
	clean, err = gitops.ValidatePath(dir, path)
	if err != nil {
		return "", "", fail(http.StatusBadRequest, err.Error())
	}
	run := gitops.Runner{Dir: dir}
	stage := false
	if staged != nil {
		stage = *staged
	} else {
		out, _, _ := run.Git(gitops.TimeoutQuery, "status", "--porcelain", "--", clean)
		trimmed := strings.TrimSpace(out)
		stage = len(trimmed) >= 2 && (trimmed[0] == ' ' || trimmed[0] == '?')
	}
	if stage {
		if _, stderr, err := run.Git(gitops.TimeoutQuery, "add", "-A", "--", clean); err != nil {
			return "", "", fail(http.StatusBadRequest, "git add failed: "+stderr)
		}
		return clean, "changed", nil
	}
	if _, _, err := run.Git(gitops.TimeoutQuery, "rev-parse", "--verify", "HEAD"); err == nil {
		run.Git(gitops.TimeoutQuery, "reset", "HEAD", "--", clean)
	} else {
		run.Git(gitops.TimeoutQuery, "rm", "--cached", "-r", "-f", "--", clean)
	}
	return clean, "untracked", nil
}

func validateFiles(dir string, files []string) ([]string, error) {
	validated := make([]string, 0, len(files))
	for _, file := range files {
		path, err := gitops.ValidatePath(dir, file)
		if err != nil {
			return nil, fail(http.StatusBadRequest, err.Error())
		}
		validated = append(validated, path)
	}
	return validated, nil
}
